"""Rasterises the large clock numerals into LVGL bitmap fonts.

LVGL's built-in Montserrat stops at 48 px and one weight. The watch face wants
much bigger digits in two weights, so those are generated here from the
Montserrat variable font (SIL Open Font License, see assets/fonts/OFL.txt).

  python tools/gen_fonts.py  -> main/assets/gen/fonts.c + fonts.h
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
TTF = ROOT / "assets" / "fonts" / "Montserrat-VariableFont.ttf"
OUT = ROOT / "main" / "assets" / "gen"

DIGITS = "0123456789:"
# name, pixel size, weight, characters
FONTS = [
    ("font_num_hero_bold", 150, 640, DIGITS),
    ("font_num_hero_light", 150, 260, DIGITS),
    ("font_num_big", 84, 520, DIGITS + ".-%"),
    ("font_num_mid", 60, 560, DIGITS + ".-%/ "),
    ("font_num_heavy", 84, 900, DIGITS),
]


def build(name, size, weight, chars):
    font = ImageFont.truetype(str(TTF), size)
    font.set_variation_by_axes([weight])
    ascent, descent = font.getmetrics()
    pad = size

    bitmap = bytearray()
    glyphs = []  # (bitmap_index, adv_w, box_w, box_h, ofs_x, ofs_y)
    codes = sorted(set(ord(c) for c in chars))
    for cp in codes:
        ch = chr(cp)
        im = Image.new("L", (size * 3, size * 3), 0)
        ImageDraw.Draw(im).text((pad, pad), ch, font=font, fill=255)
        adv = round(font.getlength(ch) * 16)
        box = im.getbbox()
        if box is None:
            glyphs.append((len(bitmap), adv, 0, 0, 0, 0))
            continue
        x0, y0, x1, y1 = box
        crop = im.crop(box)
        w, h = crop.size
        assert w < 256 and h < 256, f"{name}: glyph {ch!r} too large for LVGL's 8-bit box"
        index = len(bitmap)
        # 4 bpp, one continuous nibble stream per glyph (LVGL "plain" format).
        nib = [min(15, (p + 8) >> 4) for p in crop.getdata()]
        if len(nib) % 2:
            nib.append(0)
        for a, b in zip(nib[0::2], nib[1::2]):
            bitmap.append((a << 4) | b)
        glyphs.append((index, adv, w, h, x0 - pad, (pad + ascent) - y1))

    lo, hi = codes[0], codes[-1]
    c = []
    c.append(f"static const uint8_t {name}_bitmap[] = {{")
    for o in range(0, len(bitmap), 24):
        c.append("    " + ",".join(str(b) for b in bitmap[o:o + 24]) + ",")
    c.append("};")
    c.append(f"static const lv_font_fmt_txt_glyph_dsc_t {name}_glyphs[] = {{")
    c.append("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},")
    for (idx, adv, w, h, ox, oy) in glyphs:
        c.append(f"    {{.bitmap_index = {idx}, .adv_w = {adv}, .box_w = {w}, .box_h = {h}, "
                 f".ofs_x = {ox}, .ofs_y = {oy}}},")
    c.append("};")
    c.append(f"static const uint16_t {name}_unicode[] = {{ " + ", ".join(str(cp - lo) for cp in codes) + " };")
    c.append(f"static const lv_font_fmt_txt_cmap_t {name}_cmaps[] = {{{{")
    c.append(f"    .range_start = {lo}, .range_length = {hi - lo + 1}, .glyph_id_start = 1,")
    c.append(f"    .unicode_list = {name}_unicode, .glyph_id_ofs_list = NULL, .list_length = {len(codes)},")
    c.append("    .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY,")
    c.append("}};")
    c.append(f"static const lv_font_fmt_txt_dsc_t {name}_dsc = {{")
    c.append(f"    .glyph_bitmap = {name}_bitmap, .glyph_dsc = {name}_glyphs, .cmaps = {name}_cmaps,")
    c.append("    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = 1, .bpp = 4, .kern_classes = 0,")
    c.append("    .bitmap_format = LV_FONT_FMT_TXT_PLAIN,")
    c.append("};")
    c.append(f"const lv_font_t {name} = {{")
    c.append("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,")
    c.append("    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,")
    c.append(f"    .line_height = {ascent + descent}, .base_line = {descent},")
    c.append("    .subpx = LV_FONT_SUBPX_NONE, .underline_position = -8, .underline_thickness = 4,")
    c.append(f"    .dsc = &{name}_dsc, .fallback = NULL, .user_data = NULL,")
    c.append("};")
    c.append("")
    print(f"{name}: {size}px w{weight}, {len(codes)} glyphs, {len(bitmap) // 1024} KB")
    return c


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    c = ["/* Generated by tools/gen_fonts.py. Do not edit. */", '#include "fonts.h"', ""]
    h = ["/* Generated by tools/gen_fonts.py. Do not edit. */", "#pragma once", '#include "lvgl.h"', ""]
    for name, size, weight, chars in FONTS:
        c += build(name, size, weight, chars)
        h.append(f"extern const lv_font_t {name};")
    (OUT / "fonts.c").write_text("\n".join(c) + "\n")
    (OUT / "fonts.h").write_text("\n".join(h) + "\n")


if __name__ == "__main__":
    main()
